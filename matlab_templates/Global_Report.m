function dirs = collect_candidate_child_dirs_r2015(rootDir)
entries = dir(rootDir);
dirs = {};
for i = 1:numel(entries)
    entry = entries(i);
    if ~entry.isdir
        continue;
    end
    name = strtrim(entry.name);
    if strcmp(name, '.') || strcmp(name, '..')
