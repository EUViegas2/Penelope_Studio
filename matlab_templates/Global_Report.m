function apply_global_component_axis_scale_r2015(ax, yVals, eVals)
if nargin < 3
    eVals = zeros(size(yVals));
end

yVals = yVals(:);
eVals = eVals(:);
valid = isfinite(yVals) & yVals > 0;
if ~any(valid)
    return;
end

yVals = yVals(valid);
eVals = eVals(valid);
if isempty(eVals)
    eVals = zeros(size(yVals));
elseif numel(eVals) ~= numel(yVals)
    eVals = zeros(size(yVals));
end

positiveVals = yVals(yVals > 0);
if isempty(positiveVals)
    return;
end

spreadRatio = max(positiveVals) / max(min(positiveVals), eps);
if spreadRatio >= 50
    set(ax, 'YScale', 'log');
    return;
end

set(ax, 'YScale', 'linear');
lowVals = yVals - eVals;
highVals = yVals + eVals;
yMin = min(lowVals);
yMax = max(highVals);
if ~isfinite(yMin) || ~isfinite(yMax)
    return;
end
if yMin == yMax
    pad = max(abs(yMax) * 0.08, 1);
else
    pad = 0.08 * (yMax - yMin);
end
ylim(ax, [max(0, yMin - pad), yMax + pad]);
end

