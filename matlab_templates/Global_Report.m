function archive_existing_global_report_outputs_r2015(folderPath)
if nargin < 1 || isempty(folderPath) || ~exist(folderPath, 'dir')
    return;
end
patterns = { ...
    'Global_Report_body_totals.csv', ...
    'Global_Report_key_bodies.csv', ...
    'Global_Report*.png' ...
};
files = [];
for i = 1:numel(patterns)
    matches = dir(fullfile(folderPath, patterns{i}));
    if isempty(matches)
        continue;
    end
    files = [files; matches(:)]; %#ok<AGROW>
end
if isempty(files)
    return;
end
archiveRoot = fullfile(folderPath, 'old');
if ~exist(archiveRoot, 'dir')
    mkdir(archiveRoot);
end
archiveDir = fullfile(archiveRoot, ['Global_Report_' datestr(now, 'yyyymmdd_HHMMSS')]);
if ~exist(archiveDir, 'dir')
    mkdir(archiveDir);
end
seen = {};
for i = 1:numel(files)
    name = files(i).name;
    if any(strcmpi(seen, name))
        continue;
    end
    if strcmpi(name, 'Global_Report_prepared_totals.csv') || strcmpi(name, 'Global_Report_studio_contexts.csv')
        continue;
    end
    seen{end + 1, 1} = name; %#ok<AGROW>
    src = fullfile(folderPath, name);
    if ~exist(src, 'file')
        continue;
    end
    dst = fullfile(archiveDir, name);
    if exist(dst, 'file')
        [~, base, ext] = fileparts(name);
        dst = fullfile(archiveDir, [base '_' datestr(now, 'HHMMSSFFF') ext]);
    end
    movefile(src, dst);
end
end


