function canonical = lookup_alias_override_r2015(aliasMap, groupLabel, detectedLabel)
canonical = '';
if isempty(aliasMap) || nargin < 3 || isempty(detectedLabel)
    return;
end
detectedKey = normalize_body_compare_key_r2015(detectedLabel);
groupKey = normalize_body_compare_key_r2015(groupLabel);
for i = 1:size(aliasMap, 1)
    aliasGroupKey = '';
    if size(aliasMap, 2) >= 3
        aliasGroupKey = normalize_body_compare_key_r2015(aliasMap{i, 1});
        aliasDetected = aliasMap{i, 2};
        aliasCanonical = aliasMap{i, 3};
    else
        aliasDetected = aliasMap{i, 1};
        aliasCanonical = aliasMap{i, 2};
    end
    if strcmp(normalize_body_compare_key_r2015(aliasDetected), detectedKey) && strcmp(aliasGroupKey, groupKey)
        canonical = strtrim(char(aliasCanonical));
        return;
    end
end
for i = 1:size(aliasMap, 1)
    if size(aliasMap, 2) >= 3
        aliasGroupKey = normalize_body_compare_key_r2015(aliasMap{i, 1});
        aliasDetected = aliasMap{i, 2};
        aliasCanonical = aliasMap{i, 3};
        if ~isempty(aliasGroupKey)
            continue;
        end
    else
        aliasDetected = aliasMap{i, 1};
        aliasCanonical = aliasMap{i, 2};
    end
    if strcmp(normalize_body_compare_key_r2015(aliasDetected), detectedKey)
        canonical = strtrim(char(aliasCanonical));
        return;
    end
end
end

