function Global_Report
% Global_Report
% Bottom-up workbook combiner for grouped dose comparisons.
%
% Save this script in the master root you want to process. The script:
% 1) walks child folders bottom-up;
% 2) reuses child body_totals_by_alpha.csv or child Global_Report_body_totals.csv;
% 3) harmonizes BODY labels for cross-phantom comparisons;
% 4) writes grouped totals CSVs and plots at each level.
%
% This template is intentionally workbook-focused. It does not process
% 3d-dose.dat files.

close all;
clc;
disp(['Running Global_Report from: ' mfilename('fullpath')]);

%% ---------------- USER PARAMETERS ----------------
% selectedLabelSpecs was generated by PENELOPE Studio from user-selected SURFACE labels
%__STUDIO_SELECTED_LABELS_BEGIN__
xTumorOlhoDto = 4.0;  yTumorOlhoDto = 3.0;  zTumorOlhoDto = -2.2;
xOlhoDireito = 4.0;  yOlhoDireito = 6.5;  zOlhoDireito = -2.0;
xOlhoEsquerdo = -4.0;  yOlhoEsquerdo = 6.5;  zOlhoEsquerdo = -2.0;
selectedLabelSpecs = {
    'Tumor olho dto', 'target', xTumorOlhoDto, yTumorOlhoDto, zTumorOlhoDto;
    'Olho direito', 'body', xOlhoDireito, yOlhoDireito, zOlhoDireito;
    'Olho esquerdo', 'body', xOlhoEsquerdo, yOlhoEsquerdo, zOlhoEsquerdo
};
targetSurfaceLabel = 'Tumor olho dto';
targetBodyName = 'Tumor olho dto';
selectedBodyNames = {
    'Tumor olho dto';
    'Olho direito';
    'Olho esquerdo'
};
comparisonBodyNames = {
    'Olho direito';
    'Olho esquerdo'
};
targetIdx = [];
if ~isempty(targetSurfaceLabel) && ~isempty(selectedLabelSpecs)
    targetIdx = find(strcmpi(selectedLabelSpecs(:,1), targetSurfaceLabel), 1);
end
if isempty(targetIdx)
    xT = 0; %#ok<NASGU>
    yT = 0; %#ok<NASGU>
    zT = 0; %#ok<NASGU>
else
    xT = selectedLabelSpecs{targetIdx,3}; %#ok<NASGU>
    yT = selectedLabelSpecs{targetIdx,4}; %#ok<NASGU>
    zT = selectedLabelSpecs{targetIdx,5}; %#ok<NASGU>
end
%__STUDIO_SELECTED_LABELS_END__

% geometrySlicePoints is not used here, but the placeholder is kept so the
% template can be generated from the same Studio data model as the main
% report script.
%__STUDIO_GEOMETRY_SLICES_BEGIN__
geometrySlicePoints = struct(); %#ok<NASGU>
geometrySlicePoints.xy = zeros(0,2);
geometrySlicePoints.xz = zeros(0,2);
geometrySlicePoints.yz = zeros(0,2);
%__STUDIO_GEOMETRY_SLICES_END__

enableAliasReview = true;
maxSummarySeries = 10;

ced = [char(231) char(227)];
grau = char(176);
masterRoot = fileparts(mfilename('fullpath'));
if isempty(masterRoot) || ~exist(masterRoot, 'dir')
    chosenRoot = uigetdir(pwd, 'Select master root for Global_Report');
    if isequal(chosenRoot, 0)
        disp('No master root selected. Exiting Global_Report.');
        return;
    end
    masterRoot = chosenRoot;
end

process_global_report_root_r2015(masterRoot, masterRoot, targetBodyName, comparisonBodyNames, selectedBodyNames, enableAliasReview, maxSummarySeries, ced, grau);
disp('Global_Report finished.');
end

function T = process_global_report_root_r2015(currentRoot, masterRoot, targetBodyName, comparisonBodyNames, selectedBodyNames, enableAliasReview, maxSummarySeries, ced, grau)
disp(['Global_Report: processing root ' currentRoot]);

preparedTotalsPath = fullfile(currentRoot, 'Global_Report_prepared_totals.csv');
preparedContextsPath = fullfile(currentRoot, 'Global_Report_studio_contexts.csv');
if exist(preparedTotalsPath, 'file') && exist(preparedContextsPath, 'file')
    T = load_global_body_totals_csv_r2015(preparedTotalsPath);
    if isempty(T)
        return;
    end
    preferredNames = build_global_preferred_names_r2015(selectedBodyNames, targetBodyName, comparisonBodyNames);

    aliasPath = fullfile(currentRoot, 'Global_Report_component_aliases.csv');
    aliasMap = load_component_alias_map_r2015(aliasPath);
    if enableAliasReview
        aliasMap = prompt_component_aliases_r2015(currentRoot, T, preferredNames, aliasMap);
        write_component_alias_map_r2015(aliasPath, aliasMap);
    end
    archive_existing_global_report_outputs_r2015(currentRoot);
    rawTotals = aggregate_global_totals_r2015(T, {});
    rawTotals = sortrows(rawTotals, {'ContextLabel', 'SourceType', 'Alpha', 'Component'});
    writetable(rawTotals, fullfile(currentRoot, 'Global_Report_body_totals.csv'));

    plotTotals = T;
    if ~isempty(aliasMap)
        plotTotals.Component = apply_component_alias_map_r2015(plotTotals.Component, plotTotals.ContextLabel, aliasMap, preferredNames);
    end
    T = aggregate_global_totals_r2015(plotTotals, preferredNames);
    T = sortrows(T, {'ContextLabel', 'SourceType', 'Alpha', 'Component'});
    keyNames = build_plot_component_names_r2015(preferredNames, T.Component);
    keyTable = filter_key_components_r2015(T, keyNames);
    if ~isempty(keyTable)
        writetable(keyTable, fullfile(currentRoot, 'Global_Report_key_bodies.csv'));
        plot_global_summary_line_r2015(keyTable, keyNames, currentRoot, masterRoot, maxSummarySeries, grau);
        plot_global_component_bars_r2015(keyTable, keyNames, currentRoot, masterRoot, grau);
    end
    return;
end

childDirs = collect_candidate_child_dirs_r2015(currentRoot);
for i = 1:numel(childDirs)
    try
        process_global_report_root_r2015(childDirs{i}, masterRoot, targetBodyName, comparisonBodyNames, selectedBodyNames, enableAliasReview, maxSummarySeries, ced, grau);
    catch ME
        disp(['Global_Report: failed child root ' childDirs{i} ': ' ME.message]);
    end
end

childGlobalFiles = {};
childBatchFiles = {};
for i = 1:numel(childDirs)
    globalPath = fullfile(childDirs{i}, 'Global_Report_body_totals.csv');
    batchPath = fullfile(childDirs{i}, 'body_totals_by_alpha.csv');
    childName = folder_label_r2015(childDirs{i});
    if is_batch_folder_name_r2015(childName) && exist(batchPath, 'file')
        childBatchFiles{end + 1, 1} = batchPath; %#ok<AGROW>
    elseif exist(globalPath, 'file')
        childGlobalFiles{end + 1, 1} = globalPath; %#ok<AGROW>
    elseif exist(batchPath, 'file')
        childBatchFiles{end + 1, 1} = batchPath; %#ok<AGROW>
    end
end

T = empty_global_totals_table_r2015();

for i = 1:numel(childGlobalFiles)
    childTable = load_global_body_totals_csv_r2015(childGlobalFiles{i});
    if ~isempty(childTable)
        T = [T; childTable]; %#ok<AGROW>
    end
end

if ~isempty(childBatchFiles)
    batchTotals = aggregate_batch_children_totals_r2015(childBatchFiles, currentRoot, masterRoot, selectedBodyNames);
    if ~isempty(batchTotals)
        T = [T; batchTotals]; %#ok<AGROW>
    end
end

if isempty(T)
    return;
end

preferredNames = build_global_preferred_names_r2015(selectedBodyNames, targetBodyName, comparisonBodyNames);

aliasPath = fullfile(currentRoot, 'Global_Report_component_aliases.csv');
aliasMap = load_component_alias_map_r2015(aliasPath);
if enableAliasReview
    aliasMap = prompt_component_aliases_r2015(currentRoot, T, preferredNames, aliasMap);
    write_component_alias_map_r2015(aliasPath, aliasMap);
end
archive_existing_global_report_outputs_r2015(currentRoot);
bodyTotalsPath = fullfile(currentRoot, 'Global_Report_body_totals.csv');
rawTotals = aggregate_global_totals_r2015(T, {});
rawTotals = sortrows(rawTotals, {'ContextLabel', 'SourceType', 'Alpha', 'Component'});
writetable(rawTotals, bodyTotalsPath);

plotTotals = T;
if ~isempty(aliasMap)
    plotTotals.Component = apply_component_alias_map_r2015(plotTotals.Component, plotTotals.ContextLabel, aliasMap, preferredNames);
end

T = aggregate_global_totals_r2015(plotTotals, preferredNames);
T = sortrows(T, {'ContextLabel', 'SourceType', 'Alpha', 'Component'});

keyNames = build_plot_component_names_r2015(preferredNames, T.Component);
keyTable = filter_key_components_r2015(T, keyNames);
if ~isempty(keyTable)
    writetable(keyTable, fullfile(currentRoot, 'Global_Report_key_bodies.csv'));
    plot_global_summary_line_r2015(keyTable, keyNames, currentRoot, masterRoot, maxSummarySeries, grau);
    plot_global_component_bars_r2015(keyTable, keyNames, currentRoot, masterRoot, grau);
end
end

function T = aggregate_batch_children_totals_r2015(batchCsvFiles, currentRoot, masterRoot, preferredNames)
merged = empty_global_totals_table_r2015();
for i = 1:numel(batchCsvFiles)
    childTable = load_batch_body_totals_csv_r2015(batchCsvFiles{i});
    if isempty(childTable)
        continue;
    end
    merged = [merged; childTable]; %#ok<AGROW>
end
if isempty(merged)
    T = merged;
    return;
end

contextLabel = context_label_for_root_r2015(currentRoot, masterRoot);
contextCol = repmat({contextLabel}, height(merged), 1);
merged.ContextLabel = contextCol;
if nargin >= 4 && ~isempty(preferredNames)
    merged.Component = replace_component_labels_r2015(merged.Component, preferredNames);
end
T = aggregate_global_totals_r2015(merged, preferredNames);
end

function T = aggregate_global_totals_r2015(Tin, preferredNames)
if isempty(Tin)
    T = empty_global_totals_table_r2015();
    return;
end

contextLabels = cell_column_to_strings_r2015(Tin.ContextLabel);
sourceTypes = cell_column_to_strings_r2015(Tin.SourceType);
components = cell_column_to_strings_r2015(Tin.Component);
alphas = table_column_to_numeric_r2015(Tin.Alpha);
nFields = table_column_to_numeric_r2015(Tin.NFields);
edepEv = table_column_to_numeric_r2015(Tin.Edep_eV);
dEdepEv = table_column_to_numeric_r2015(Tin.dEdep_eV);
doseEvg = table_column_to_numeric_r2015(Tin.Dose_eVg);
dDoseEvg = table_column_to_numeric_r2015(Tin.dDose_eVg);
doseGy = table_column_to_numeric_r2015(Tin.Dose_Gy);
dDoseGy = table_column_to_numeric_r2015(Tin.dDose_Gy);

componentKeys = build_body_key_list_r2015(components);
sourceKeys = sourceTypes;
contextKeys = contextLabels;

 outContext = {};
 outSource = {};
 outAlpha = [];
 outComponent = {};
 outNFields = [];
 outEdepEv = [];
 outdEdepEv = [];
 outDoseEvg = [];
 outdDoseEvg = [];
 outErrPct = [];
 outDoseGy = [];
 outdDoseGy = [];
 uniqueContexts = unique_stable_strings_r2015(contextKeys);
for i = 1:numel(uniqueContexts)
    contextMask = strcmp(contextKeys, uniqueContexts{i});
    uniqueSources = unique_stable_strings_r2015(sourceKeys(contextMask));
    for s = 1:numel(uniqueSources)
        sourceMask = contextMask & strcmp(sourceKeys, uniqueSources{s});
        alphaList = unique(alphas(sourceMask));
        alphaList = alphaList(isfinite(alphaList));
        alphaList = sort(alphaList(:)');
        for a = 1:numel(alphaList)
            alphaMask = sourceMask & (alphas == alphaList(a));
            compKeys = unique_stable_strings_r2015(componentKeys(alphaMask));
            for c = 1:numel(compKeys)
                compMask = alphaMask & strcmp(componentKeys, compKeys{c});
                firstIdx = find(compMask, 1, 'first');
                if isempty(firstIdx)
                    continue;
                end
                doseEvgValue = sum(doseEvg(compMask));
                dDoseEvgValue = sqrt(sum(dDoseEvg(compMask).^2));
                if doseEvgValue ~= 0
                    errPctValue = 100 * dDoseEvgValue / doseEvgValue;
                else
                    errPctValue = NaN;
                end
                outContext{end + 1, 1} = contextLabels{firstIdx}; %#ok<AGROW>
                outSource{end + 1, 1} = normalize_source_type_label_r2015(sourceTypes{firstIdx}); %#ok<AGROW>
                outAlpha(end + 1, 1) = alphaList(a); %#ok<AGROW>
                outComponent{end + 1, 1} = preferred_body_display_label_r2015(components{firstIdx}, preferredNames); %#ok<AGROW>
                outNFields(end + 1, 1) = sum(nFields(compMask)); %#ok<AGROW>
                outEdepEv(end + 1, 1) = sum(edepEv(compMask)); %#ok<AGROW>
                outdEdepEv(end + 1, 1) = sqrt(sum(dEdepEv(compMask).^2)); %#ok<AGROW>
                outDoseEvg(end + 1, 1) = doseEvgValue; %#ok<AGROW>
                outdDoseEvg(end + 1, 1) = dDoseEvgValue; %#ok<AGROW>
                outErrPct(end + 1, 1) = errPctValue; %#ok<AGROW>
                outDoseGy(end + 1, 1) = sum(doseGy(compMask)); %#ok<AGROW>
                outdDoseGy(end + 1, 1) = sqrt(sum(dDoseGy(compMask).^2)); %#ok<AGROW>
            end
        end
    end
end
T = table( ...
    outContext, outSource, outAlpha, outComponent, outNFields, ...
    outEdepEv, outdEdepEv, outDoseEvg, outdDoseEvg, outErrPct, outDoseGy, outdDoseGy, ...
    'VariableNames', { ...
        'ContextLabel', 'SourceType', 'Alpha', 'Component', 'NFields', ...
        'Edep_eV', 'dEdep_eV', 'Dose_eVg', 'dDose_eVg', 'Error_pct', 'Dose_Gy', 'dDose_Gy' ...
    });
end

