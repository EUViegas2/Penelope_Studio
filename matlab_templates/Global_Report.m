function T = filter_key_components_r2015(Tin, keyNames)
if isempty(Tin)
    T = Tin;
    return;
end
keyKeys = build_body_key_list_r2015(keyNames);
componentKeys = build_body_key_list_r2015(Tin.Component);
keepMask = false(height(Tin), 1);
for i = 1:numel(keyKeys)
    keepMask = keepMask | strcmp(componentKeys, keyKeys{i});
end
T = Tin(keepMask, :);
if ~isempty(T)
    T.Component = replace_component_labels_r2015(T.Component, keyNames);
end
end

function plot_global_summary_line_r2015(K, keyNames, currentRoot, masterRoot, maxSummarySeries, grau)
seriesInfo = unique_context_source_alpha_rows_r2015(K, currentRoot, masterRoot);
if height(seriesInfo) > maxSummarySeries
    disp(['Global_Report: skipping summary line plot in ', currentRoot, ' because there are ', num2str(height(seriesInfo)), ' series.']);
    return;
end

legendSeed = cell(height(seriesInfo), 1);
for i = 1:height(seriesInfo)
    legendSeed{i} = sprintf('%s | alpha = %.4g%c', seriesInfo.DisplayLabel{i}, seriesInfo.Alpha(i), grau);
end
plotWidth = max(860, 150 * numel(keyNames));
legendWidth = max(460, 7 * max_cell_string_length_r2015(legendSeed) + 120);
figWidth = plotWidth + legendWidth + 140;
fig = figure('Color', 'w', 'Position', [100, 100, figWidth, 580]);
ax = axes('Parent', fig, 'Position', [0.08 0.14 0.60 0.78]);
hold(ax, 'on');
legendLabels = {};

for i = 1:height(seriesInfo)
    rowMask = strcmp(K.ContextLabel, seriesInfo.ContextLabel{i}) & ...
              strcmp(K.SourceType, seriesInfo.SourceType{i}) & ...
              K.Alpha == seriesInfo.Alpha(i);
    Ka = K(rowMask, :);
    orderedIdx = zeros(numel(keyNames), 1);
    for j = 1:numel(keyNames)
        matchIdx = find_component_row_r2015(Ka.Component, keyNames{j});
        if ~isempty(matchIdx)
            orderedIdx(j) = matchIdx;
        end
    end
    xVals = find(orderedIdx > 0);
    if isempty(xVals)
        continue;
    end
    Ka = Ka(orderedIdx(xVals), :);
    errorbar(ax, xVals, Ka.Dose_eVg, Ka.dDose_eVg, 'o-');
    legendLabels{end + 1, 1} = sprintf('%s | alpha = %.4g%c', seriesInfo.DisplayLabel{i}, seriesInfo.Alpha(i), grau); %#ok<AGROW>
end

set(ax, 'YScale', 'log', 'XTick', 1:numel(keyNames), 'XTickLabel', keyNames);
try
    set(ax, 'XTickLabelRotation', 25);
catch
end
xlim([0.5, numel(keyNames) + 0.5]);
ylabel('Dose total somada (eV/g)');
title(sprintf('Global_Report: dose total por corpo selecionado (%s)', folder_label_r2015(currentRoot)), 'Interpreter', 'none');
grid on;
if ~isempty(legendLabels)
    lgd = legend(ax, legendLabels, 'Location', 'eastoutside', 'Interpreter', 'none');
    apply_global_right_legend_layout_r2015(ax, lgd, [0.08 0.14 0.60 0.78], 0.72);
end
drawnow;
saveas(fig, fullfile(currentRoot, 'Global_Report_key_bodies_by_series.png'));
close(fig);
end

function plot_global_component_bars_r2015(K, keyNames, currentRoot, masterRoot, grau)
alphaList = unique(K.Alpha);
alphaList = alphaList(isfinite(alphaList));
alphaList = sort(alphaList(:)');
if isempty(K) || isempty(alphaList)
    return;
end

keyNames = build_plot_component_names_r2015(keyNames, K.Component);
if isempty(keyNames)
    return;
end

componentKeysAll = build_body_key_list_r2015(K.Component);
familyLabels = cell(numel(keyNames), 1);
for i = 1:numel(keyNames)
    familyLabels{i} = component_family_label_r2015(keyNames{i});
end
uniqueFamilies = unique_stable_strings_r2015(familyLabels);

for f = 1:numel(uniqueFamilies)
    memberMask = strcmp(familyLabels, uniqueFamilies{f});
    memberNames = keyNames(memberMask);
    if isempty(memberNames)
        continue;
    end

    if numel(memberNames) > 1
        memberKeys = build_body_key_list_r2015(memberNames);
        familyMask = false(height(K), 1);
        for m = 1:numel(memberKeys)
            familyMask = familyMask | strcmp(componentKeysAll, memberKeys{m});
        end
        Kfamily = K(familyMask, :);
        plot_global_component_family_r2015(Kfamily, memberNames, uniqueFamilies{f}, currentRoot, masterRoot, grau);
        continue;
    end

    compName = memberNames{1};
    compKey = normalize_body_compare_key_r2015(compName);
    compMask = strcmp(componentKeysAll, compKey);
    Kc = K(compMask, :);
    if isempty(Kc)
        continue;
    end

    seriesInfo = unique_context_source_rows_r2015(Kc, currentRoot, masterRoot);
    if isempty(seriesInfo)
        continue;
    end

    y = nan(height(seriesInfo), numel(alphaList));
    e = nan(height(seriesInfo), numel(alphaList));
    for i = 1:height(seriesInfo)
        for a = 1:numel(alphaList)
            rowMask = strcmp(Kc.ContextLabel, seriesInfo.ContextLabel{i}) & ...
                      strcmp(Kc.SourceType, seriesInfo.SourceType{i}) & ...
                      Kc.Alpha == alphaList(a);
            idx = find(rowMask, 1, 'first');
            if isempty(idx)
                continue;
            end
            y(i, a) = Kc.Dose_eVg(idx);
            e(i, a) = Kc.dDose_eVg(idx);
        end
    end

    validRows = any(isfinite(y), 2);
    if ~any(validRows)
        continue;
    end
    y = y(validRows, :);
    e = e(validRows, :);
    seriesInfo = seriesInfo(validRows, :);

    if height(seriesInfo) == 1
        plot_global_component_single_context_r2015(compName, y(1, :), e(1, :), alphaList, seriesInfo.DisplayLabel{1}, currentRoot, grau);
        continue;
    end

    if numel(alphaList) == 1
        plot_global_component_single_alpha_r2015(compName, y(:, 1), e(:, 1), seriesInfo.DisplayLabel, alphaList(1), currentRoot, grau);
        continue;
    end

    plotWidth = max(900, 140 * height(seriesInfo));
    legendWidth = max(260, 150 * numel(alphaList));
    figWidth = plotWidth + legendWidth + 140;
    fig = figure('Color', 'w', 'Position', [100, 100, figWidth, 620]);
    ax = axes('Parent', fig, 'Position', [0.08 0.14 0.64 0.78]);
    bar(ax, y, 'grouped');
    hold(ax, 'on');
    groupWidth = min(0.8, numel(alphaList) / (numel(alphaList) + 1.5));
    for a = 1:numel(alphaList)
        x = (1:height(seriesInfo)) - groupWidth/2 + (2 * a - 1) * groupWidth / (2 * numel(alphaList));
        valid = isfinite(y(:, a)) & isfinite(e(:, a));
        if any(valid)
            errorbar(ax, x(valid), y(valid, a), e(valid, a), 'k', 'LineStyle', 'none', 'LineWidth', 1.1);
        end
    end
    hold(ax, 'off');
    set(ax, 'XTick', 1:height(seriesInfo), 'XTickLabel', seriesInfo.DisplayLabel);
    try
        set(ax, 'XTickLabelRotation', 25);
    catch
    end
    apply_global_component_axis_scale_r2015(ax, y(:), e(:));
    ylabel('Dose total somada (eV/g)');
    xlabel('Contexto / fonte');
    title(sprintf('Global_Report: %s por contexto (%s)', compName, folder_label_r2015(currentRoot)), 'Interpreter', 'none');
    lgd = legend(ax, build_alpha_legend_r2015(alphaList, grau), 'Location', 'eastoutside');
    apply_global_right_legend_layout_r2015(ax, lgd, [0.08 0.14 0.64 0.78], 0.76);
    grid on;
    drawnow;
    saveas(fig, fullfile(currentRoot, ['Global_Report_component_' safe_label_file_token_r2015(compName) '_by_context.png']));
    close(fig);
end
end

function plot_global_component_family_r2015(Kf, memberNames, familyLabel, currentRoot, masterRoot, grau)
if isempty(Kf) || isempty(memberNames)
    return;
end

seriesInfo = unique_context_source_alpha_rows_r2015(Kf, currentRoot, masterRoot);
if isempty(seriesInfo)
    return;
end

memberNames = build_plot_component_names_r2015(memberNames, Kf.Component);
if numel(memberNames) < 2
    return;
end

