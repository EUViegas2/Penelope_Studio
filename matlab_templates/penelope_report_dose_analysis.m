function [handles, names] = plot_profile_markers_r2015(labelSpecs, axisMode, yMin, yMax)
handles = [];
names = {};
if isempty(labelSpecs)
    return;
end
palette = lines(max(1, size(labelSpecs, 1) - 1));
bodyCounter = 0;
for idx = 1:size(labelSpecs, 1)
    row = labelSpecs(idx, :);
    if numel(row) == 1 && iscell(row{1})
        row = row{1};
    end
    if numel(row) < 5
        continue;
    end
    label = char(row{1});
    markerMode = lower(strtrim(char(row{2})));
    coordVal = coordinate_for_axis_r2015(row{3}, row{4}, row{5}, axisMode);
    if ~isfinite(coordVal)
        continue;
    end
    if strcmp(markerMode, 'target') || strcmp(markerMode, 'o')
        h = draw_vertical_marker_r2015(coordVal, yMin, yMax, [0 0 0], ':', 1.2);
    else
        bodyCounter = bodyCounter + 1;
        clr = palette(1 + mod(bodyCounter - 1, size(palette, 1)), :);
        h = draw_vertical_marker_r2015(coordVal, yMin, yMax, clr, '--', 0.9);
    end
    handles(end + 1, 1) = h; %#ok<AGROW>
    names{end + 1} = label; %#ok<AGROW>
end
end

