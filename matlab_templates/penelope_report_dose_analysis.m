function process_grouped_3d_dose_folder_r2015(groupDir, xT, yT, zT, labelSpecs, geometrySlicePoints, ced)
files = dir(fullfile(groupDir, '3d-dose_case*.dat'));
if isempty(files)
    files = dir(fullfile(groupDir, '3d-dose*.dat'));
end
if isempty(files)
    return;
end
[~, order] = sort({files.name});
files = files(order);

d = 0.5;
totalDoseUnitLabel = 'Dose total (eV/g)';

for k = 1:numel(files)
    dosePath = fullfile(groupDir, files(k).name);
    Scur = load_3d_dose_r2015(dosePath);
    if k == 1
        x = Scur(:,1);
        y = Scur(:,2);
        z = Scur(:,3);
        ix = round(Scur(:,6));
        iy = round(Scur(:,7));
        iz = round(Scur(:,8));
        doseT = zeros(size(x));
        uTotal2 = zeros(size(x));
    else
        if size(Scur, 1) ~= numel(x)
            error('Grid size mismatch in "%s": expected %d voxel rows (from first file), got %d. All grouped 3d-dose files must share the same grid.', ...
                files(k).name, numel(x), size(Scur, 1));
        end
    end
    doseT = doseT + Scur(:,4);
    if size(Scur, 2) >= 5
        uTotal2 = uTotal2 + (Scur(:,5) .^ 2);
    end
end
uTotal = sqrt(uTotal2);
nx = max(ix);
ny = max(iy);
nz = max(iz);
D = nan(nx, ny, nz);
U = nan(nx, ny, nz);
lin = sub2ind([nx, ny, nz], ix, iy, iz);
D(lin) = doseT;
U(lin) = uTotal;
xVec = accumarray(ix, x, [nx 1], @mean);
yVec = accumarray(iy, y, [ny 1], @mean);
zVec = accumarray(iz, z, [nz 1], @mean);
[~, ixt] = min(abs(xVec - xT));
